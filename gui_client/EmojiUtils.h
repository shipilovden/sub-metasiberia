inline const std::vector<std::string_view>& supportedEmoji()
{
	static const std::vector<std::string_view> emojis = []() {
		std::vector<std::string_view> out;
		const auto& categories = emojiCategories();
		for(size_t i=0; i<categories.size(); ++i)
			for(size_t z=0; z<categories[i].emojis.size(); ++z)
				out.push_back(categories[i].emojis[z].emoji);
		return out;
	}();
	return emojis;
}


inline std::string_view emojiDisplayName(std::string_view text)
{
	const auto& categories = emojiCategories();
	for(size_t i=0; i<categories.size(); ++i)
	{
		for(size_t z=0; z<categories[i].emojis.size(); ++z)
		{
			if(categories[i].emojis[z].emoji == text)
				return categories[i].emojis[z].name;
		}
	}

	return "emoji";
}


// Search metadata includes every category/name for emoji shared by multiple groups.
// Unsupported emoji have no search text. The returned text is UTF-8, not a display label.
inline std::string emojiSearchText(std::string_view emoji)
{
	std::string text;
	for(const auto& category : emojiCategories())
		for(const auto& definition : category.emojis)
			if(definition.emoji == emoji)
			{
				if(text.empty())
					text = std::string(emoji);
				text += " ";
				text += category.title;
				text += " ";
				text += definition.name;
				if(!definition.aliases.empty())
				{
					text += " ";
					text += definition.aliases;
				}
			}
	return text;
}


namespace detail
{
// Validate UTF-8 before substring matching, so partial/invalid bytes cannot match emoji.
// Fold only ASCII and Russian letters (including Yo); preserve all other codepoints.
inline bool foldEmojiSearchText(std::string_view text, std::string& out)
{
	out.clear();
	out.reserve(text.size());
	for(size_t i=0; i<text.size();)
	{
		const size_t start = i;
		const unsigned char first = static_cast<unsigned char>(text[i++]);
		unsigned int cp = first;
		unsigned int minimum = 0;
		size_t trailing = 0;
		if(first >= 0xC2 && first <= 0xDF) { cp = first & 0x1F; trailing = 1; minimum = 0x80; }
		else if(first >= 0xE0 && first <= 0xEF) { cp = first & 0x0F; trailing = 2; minimum = 0x800; }
		else if(first >= 0xF0 && first <= 0xF4) { cp = first & 0x07; trailing = 3; minimum = 0x10000; }
		else if(first >= 0x80) return false;
		if(trailing > text.size() - i) return false;
		for(size_t n=0; n<trailing; ++n)
		{
			const unsigned char byte = static_cast<unsigned char>(text[i++]);
			if((byte & 0xC0) != 0x80) return false;
			cp = (cp << 6) | (byte & 0x3F);
		}
		if(cp < minimum || cp > 0x10FFFF || (cp >= 0xD800 && cp <= 0xDFFF)) return false;

		if(cp >= 'A' && cp <= 'Z')
			out.push_back(static_cast<char>(cp + ('a' - 'A')));
		else if((cp >= 0x410 && cp <= 0x42F) || cp == 0x401)
		{
			cp = cp == 0x401 ? 0x451 : cp + 0x20;
			out.push_back(static_cast<char>(0xC0 | (cp >> 6)));
			out.push_back(static_cast<char>(0x80 | (cp & 0x3F)));
		}
		else
			out.append(text.data() + start, i - start);
	}
	return true;
}
}


// Case-insensitive substring search, in catalog order, with one result per emoji.
// Empty/ASCII-whitespace queries return the full unique catalog; invalid UTF-8 returns none.
// The immutable index and result count are bounded by the supported catalog.
inline std::vector<std::string> searchEmoji(const std::string& query)
{
	std::string needle;
	if(!detail::foldEmojiSearchText(query, needle))
		return {};
	const size_t first = needle.find_first_not_of(" \t\r\n\f\v");
	if(first == std::string::npos)
		needle.clear();
	else
		needle = needle.substr(first, needle.find_last_not_of(" \t\r\n\f\v") - first + 1);

	struct SearchEntry { std::string emoji; std::string text; };
	static const std::vector<SearchEntry> index = []() {
		std::vector<SearchEntry> entries;
		for(const auto emoji : supportedEmoji())
		{
			if(std::find_if(entries.begin(), entries.end(), [emoji](const SearchEntry& entry) {
				return entry.emoji == emoji;
			}) != entries.end())
				continue;
			std::string text;
			if(detail::foldEmojiSearchText(emojiSearchText(emoji), text))
				entries.push_back({std::string(emoji), text});
		}
		return entries;
	}();

	std::vector<std::string> result;
	for(const auto& entry : index)
		if(entry.text.find(needle) != std::string::npos)
			result.push_back(entry.emoji);
	return result;
}


inline std::vector<EmojiPickerCategory> buildPickerCategories(const std::vector<std::string>& recent_emojis)
{
	std::vector<EmojiPickerCategory> out;
	out.reserve(1 + emojiCategories().size());

	EmojiPickerCategory recent_category;
	recent_category.title = std::string(recentCategoryTitle());
	recent_category.num_columns = recentEmojiColumns();
	for(size_t i=0; i<recent_emojis.size(); ++i)
	{
		if(!isSupportedEmoji(recent_emojis[i]))
			continue;

		bool duplicate = false;
		for(size_t z=0; z<recent_category.emojis.size(); ++z)
		{
			if(recent_category.emojis[z] == recent_emojis[i])
			{
				duplicate = true;
				break;
			}
		}

		if(!duplicate)
			recent_category.emojis.push_back(recent_emojis[i]);

		if(recent_category.emojis.size() >= maxRecentEmojiCount())
			break;
	}
	out.push_back(recent_category);

	const auto& categories = emojiCategories();
	for(size_t i=0; i<categories.size(); ++i)
	{
		EmojiPickerCategory picker_category;
		picker_category.title = std::string(categories[i].title);
		picker_category.num_columns = categories[i].num_columns;
		picker_category.emojis.reserve(categories[i].emojis.size());
		for(size_t z=0; z<categories[i].emojis.size(); ++z)
			picker_category.emojis.push_back(std::string(categories[i].emojis[z].emoji));
		out.push_back(picker_category);
	}

	return out;
}


inline std::string pickerButtonLabel()
{
	return std::string("\xF0\x9F\x98\x80");
}


inline bool isSupportedEmoji(std::string_view text)
{
	const auto& emojis = supportedEmoji();
	for(size_t i=0; i<emojis.size(); ++i)
	{
		if(emojis[i] == text)
			return true;
	}
	return false;
}


inline void test()
{
	assert(emojiCategories().size() >= 8);
	assert(supportedEmoji().size() >= 200);
	assert(isSupportedEmoji(supportedEmoji()[0]));
	assert(isSupportedEmoji(supportedEmoji()[supportedEmoji().size() - 1]));
	assert(emojiDisplayName(supportedEmoji()[0]) != "emoji");
	assert(!isSupportedEmoji(""));
	assert(!isSupportedEmoji("hello"));
	assert(!isSupportedEmoji(std::string(supportedEmoji()[0]) + "!"));

	for(size_t i=0; i<supportedEmoji().size(); ++i)
		assert(supportedEmoji()[i].find("\xE2\x80\x8D") == std::string_view::npos);
}

